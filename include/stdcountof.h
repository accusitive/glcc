/* C2y <stdcountof.h>: the `countof` spelling for the `_Countof` operator.
 * glcc accepts `_Countof` as an extension in its permissive dialects, so
 * this header also works there; the operator itself is C2y.
 */
#ifndef __STDCOUNTOF_H
#define __STDCOUNTOF_H

#define countof _Countof

#endif /* __STDCOUNTOF_H */
